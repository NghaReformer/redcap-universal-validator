    /* =====================================================================
     * I-03  the fingerprint covers the rule SET, not its order
     * ===================================================================== */
    {
        $P = '\INSPIRE\UniversalValidator\Scan\ScanPlanner';
        $r1 = ['type' => 'assert', 'fields' => ['f1'], 'assert' => "[f1]='A'", '_origin' => 'annotation'];
        $r2 = ['type' => 'assert', 'fields' => ['f2'], 'assert' => "[f2]='B'", '_origin' => 'annotation'];
        $r3 = ['type' => 'assert', 'fields' => ['f3'], 'assert' => "[f3]='C'", '_origin' => 'annotation'];

        $req = function ($rules) {
            return ['rules' => $rules, 'engine' => '1.0', 'ownership' => [],
                    'structure' => [], 'choices' => [], 'policy' => []];
        };
        // plan() needs a store and a source to run end to end, so reach the
        // fingerprint the way plan() does instead: identify, spec, hash.
        $fpOf = function ($rules) use ($P) {
            $ids = $P::identifyAll($rules);
            $spec = [];
            foreach ($ids as $id) {
                $spec[] = ['id' => $id['source_id'], 'rev' => $id['revision'], 'origin' => $id['origin']];
            }
            usort($spec, function ($a, $b) {
                $c = strcmp($a['id'], $b['id']);
                return $c !== 0 ? $c : strcmp($a['rev'], $b['rev']);
            });
            return $P::fingerprint(['engine' => '1.0', 'rules' => $spec, 'ownership' => [],
                                    'structure' => [], 'choices' => [],
                                    'gapPolicy' => 'separate', 'valueMode' => 'locations']);
        };

        check('I-03: reordering the rule list does not move the fingerprint',
            $fpOf([$r1, $r2, $r3]) === $fpOf([$r3, $r1, $r2]));
        check('I-03: but EDITING a rule does',
            $fpOf([$r1, $r2, $r3])
            !== $fpOf([$r1, $r2, ['type' => 'assert', 'fields' => ['f3'],
                                  'assert' => "[f3]='CHANGED'", '_origin' => 'annotation']]));
        check('I-03: and so does removing one',
            $fpOf([$r1, $r2, $r3]) !== $fpOf([$r1, $r2]));
    }

    /* =====================================================================
     * I-04  identifyAll answers with the keys it was asked with
     * ===================================================================== */
    {
        $P = '\INSPIRE\UniversalValidator\Scan\ScanPlanner';
        $sparse = [
            0 => ['type' => 'assert', 'fields' => ['f1'], 'assert' => "[f1]='A'", '_origin' => 'annotation'],
            2 => ['type' => 'assert', 'fields' => ['f3'], 'assert' => "[f3]='C'", '_origin' => 'annotation'],
            5 => ['type' => 'assert', 'fields' => ['f6'], 'assert' => "[f6]='F'", '_origin' => 'settings'],
        ];
        $ids = $P::identifyAll($sparse);
        check('I-04: the answer carries the caller\'s keys, gaps and all',
            array_keys($ids) === [0, 2, 5]);
        check('I-04: and one entry per rule', count($ids) === 3);
        check('I-04: origin is read from the rule, with no positional count supplied',
            $ids[5]['origin'] === 'settings' && $ids[0]['origin'] === 'annotation');
        check('I-04: a settings rule without a stored uid still gets a settings name',
            strpos($ids[5]['source_id'], 'set:') === 0);

        // The deprecated positional fallback still answers for an untagged list,
        // so an external caller is not broken by the change.
        $untagged = [
            ['type' => 'assert', 'fields' => ['f1'], 'assert' => "[f1]='A'"],
            ['type' => 'assert', 'fields' => ['f2'], 'assert' => "[f2]='B'"],
        ];
        $legacy = $P::identifyAll($untagged, 1);
        check('I-04: the positional fallback still names an untagged list',
            $legacy[0]['origin'] === 'settings' && $legacy[1]['origin'] === 'annotation');

        // Origin must not enter the content hash: it is already in the prefix,
        // and hashing it would churn every stored revision for nothing.
        $bare = ['type' => 'assert', 'fields' => ['f1'], 'assert' => "[f1]='A'"];
        $tagged = $bare; $tagged['_origin'] = 'annotation';
        check('I-04: tagging a rule with its origin does not change its revision',
            $P::revision($bare) === $P::revision($tagged));
    }

    /* =====================================================================
     * I-05  a settings rule keeps its name when the list is reordered
     *
     * identify() has always preferred a persistent id stored on the row, and
     * its comment has always said why: an id "survives editing the rule -
     * which is the one thing a content hash cannot do". Nothing ever minted
     * one, so every project ran the content-hash fallback.
     *
     * That fallback is worse than merely fragile. revision() deliberately
     * discards the field list, so two rules of the same kind and options on
     * DIFFERENT fields hash identically and are separated only by an occurrence
     * counter assigned in list order. Dragging one row above the other swapped
     * their identities, and every finding stored against them was silently
     * re-attributed to the other rule.
     * ===================================================================== */
    {
        $D = dict(['record_id' => ['fa'], 'x_val' => ['fa'], 'y_val' => ['fa']]);
        $data = [1 => [1 => ['record_id' => '1', 'x_val' => '', 'y_val' => '']]];
        // Two rows identical in everything revision() hashes, differing only in
        // the field - which is precisely what revision() throws away.
        $rowX = ['rule-type' => 'required', 'fields' => ['x_val']];
        $rowY = ['rule-type' => 'required', 'fields' => ['y_val']];

        // Before minting: the content-hash fallback, and the swap it permits.
        $before  = identitiesByField(mkMod($D, $data, [$rowX, $rowY]), 1);
        $swapped = identitiesByField(mkMod($D, $data, [$rowY, $rowX]), 1);
        check('I-05: the premise - both rows produce a finding',
            isset($before['x_val'], $before['y_val'], $swapped['x_val'], $swapped['y_val']));
        check('I-05: without an id, reordering the rows renames the rules',
            $before['x_val'] !== $swapped['x_val']);

        // Mint. This is what a settings save now does.
        $m = mkMod($D, $data, [$rowX, $rowY]);
        $m->redcap_module_save_configuration(PID);
        $minted = $m->subSettings;
        check('I-05: every row is given an id',
            isset($minted[0]['rule-uid'], $minted[1]['rule-uid'])
            && preg_match('/^[0-9a-f]{16}\z/', $minted[0]['rule-uid'])
            && preg_match('/^[0-9a-f]{16}\z/', $minted[1]['rule-uid']));
        check('I-05: and the two ids differ',
            $minted[0]['rule-uid'] !== $minted[1]['rule-uid']);

        // An id already present is never reissued: a changed id orphans stored
        // findings, which is strictly worse than never having had one.
        $again = mkMod($D, $data, $minted);
        $again->redcap_module_save_configuration(PID);
        check('I-05: a second save does not reissue an id that already exists',
            $again->subSettings[0]['rule-uid'] === $minted[0]['rule-uid']
            && $again->subSettings[1]['rule-uid'] === $minted[1]['rule-uid']);

        // THE PROPERTY. With ids, the name follows the ROW rather than the
        // position, so dragging rows in the dialog cannot re-attribute a finding.
        $withIds     = identitiesByField(mkMod($D, $data, $minted), 1);
        $withIdsSwap = identitiesByField(mkMod($D, $data, [$minted[1], $minted[0]]), 1);
        check('I-05: an identified rule is named by its id',
            strpos($withIds['x_val'], 'uid:') === 0);
        check('I-05: and reordering the rows no longer renames it',
            $withIds['x_val'] === $withIdsSwap['x_val']
            && $withIds['y_val'] === $withIdsSwap['y_val']);
        check('I-05: while the two rules still have two names',
            $withIds['x_val'] !== $withIds['y_val']);
    }

    /* =====================================================================
     * I-06  two hidden options ticked on one checkbox are TWO findings
     *
     * A @UVCHOICES rule on a CHECKBOX emits one finding per ticked hidden code,
     * all with reason `hidden-choice` and all at the same record, event,
     * instance, form and field, under the same rule. The identity hashed
     * exactly those seven facts, so the two were byte-identical: the unique key
     * refused the second, commitBatch rolled the WHOLE batch back, and a FIRST
     * scan of a fresh project stored nothing at all for records it had examined
     * correctly. No prior scan involved, no second run needed.
     *
     * The fix is a within-location discriminator inside the hash - the ticked
     * choice CODE - and NOT an ordinal. An ordinal renumbers every later
     * finding when an earlier one is fixed, so a re-scan would close and reopen
     * rows that never changed, which destroys the one property the identity
     * exists to provide. The second half of this block is what pins that.
     * ===================================================================== */
    {
        $D = ['record_id' => ['field_type' => 'text', 'form_name' => 'fa', 'field_annotation' => ''],
              'symptoms'  => ['field_type' => 'checkbox', 'form_name' => 'fa',
                              'select_choices_or_calculations' => '1, Cough | 2, Fever | 3, Rash',
                              'field_annotation' => '@UVCHOICES={"hide":["2","3"]}']];
        // BOTH hidden options ticked. REDCap presents a checkbox as a map of
        // code => '1', which is the shape the rule reads.
        $data = [1 => [1 => ['record_id' => '1',
                             'symptoms' => ['1' => '1', '2' => '1', '3' => '1']]]];

        $m = mkMod($D, $data);
        $ctx = $m->durableScanContext(PID, ['valueCeiling' => 'locations',
                                            'generation' => 3, 'runSeq' => 3]);
        check('I-06: the premise - the checkbox rule is scannable',
            !empty($ctx['ok']));
        if (!empty($ctx['ok'])) {
            $ev = $ctx['evaluate'];
            $r  = $ev(1, $data[1]);

            $hidden = [];
            foreach ($r['findings'] as $f) {
                if ($f['reason_code'] === \INSPIRE\UniversalValidator\Scan\ReasonCode::code('hidden-choice')) {
                    $hidden[] = $f;
                }
            }
            check('I-06: both ticked hidden options are reported, not one',
                count($hidden) === 2);
            check('I-06: and they are two DIFFERENT findings, which the unique key can hold',
                count($hidden) === 2
                && $hidden[0]['identity'] !== $hidden[1]['identity']);
            check('I-06: nothing was collapsed to get there',
                isset($r['collapsed']) && $r['collapsed'] === 0);
            // The two are at ONE location by every other measure. If any of
            // these stopped being equal the test would be passing for the wrong
            // reason - two findings that differ in their field are not the case
            // this block is about.
            check('I-06: at the same field, rule and reason - only the option differs',
                count($hidden) === 2
                && $hidden[0]['field'] === $hidden[1]['field']
                && $hidden[0]['rule_source_id'] === $hidden[1]['rule_source_id']
                && $hidden[0]['reason_code'] === $hidden[1]['reason_code']
                && $hidden[0]['host_form'] === $hidden[1]['host_form']);

            // STABILITY, which is the whole reason the discriminator is the
            // choice code rather than a counter. Scan the same record again and
            // the same two identities must come back - otherwise an incremental
            // run closes and reopens rows nothing changed.
            $again = $ev(1, $data[1]);
            $ids1 = []; foreach ($hidden as $f) $ids1[] = bin2hex($f['identity']);
            $ids2 = [];
            foreach ($again['findings'] as $f) {
                if ($f['reason_code'] === \INSPIRE\UniversalValidator\Scan\ReasonCode::code('hidden-choice')) {
                    $ids2[] = bin2hex($f['identity']);
                }
            }
            sort($ids1); sort($ids2);
            check('I-06: and a re-scan produces the same two identities', $ids1 === $ids2);

            // UNTICKING ONE MUST NOT RENAME THE OTHER. This is the property an
            // ordinal discriminator would fail: with a counter, removing the
            // first finding renumbers the second, and every stored row for it
            // is orphaned.
            // THE SAME evaluator, a different reading of the record. A second
            // module would mint a second HMAC key and every identity would
            // differ for a reason that has nothing to do with the rule - which
            // would make this check pass or fail on the fixture rather than on
            // the behaviour.
            $one = [1 => ['record_id' => '1',
                          'symptoms' => ['1' => '1', '2' => '0', '3' => '1']]];
            $r2 = $ev(1, $one);
            $left = [];
            foreach ($r2['findings'] as $f) {
                if ($f['reason_code'] === \INSPIRE\UniversalValidator\Scan\ReasonCode::code('hidden-choice')) {
                    $left[] = bin2hex($f['identity']);
                }
            }
            check('I-06: unticking one hidden option leaves exactly the other',
                count($left) === 1);
            check('I-06: and does NOT rename it, which an ordinal would have',
                count($left) === 1 && in_array($left[0], $ids1, true));
        }
    }

    echo "scan_identity_php: $n checks, $fail failure(s)\n";
    exit($fail ? 1 : 0);
}
