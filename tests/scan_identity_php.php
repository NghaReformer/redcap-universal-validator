<?php
/**
 * scan_identity_php.php — WHICH RULE a durable finding is filed against.
 *
 * This suite exists because of a specific hole. Nothing in tests/ has ever
 * referenced durableScanContext() or durableEvaluateRecord(), and that is the
 * seam where the rule engine's output becomes database rows: where the host
 * form, the value preview, the uniqueness candidate key and — the subject here
 * — the rule identity are decided. Every live pilot of the durable scan died at
 * that seam, and the 22 mocked suites plus 286 real-database checks stayed green
 * through all of them.
 *
 * What it locks:
 *
 *   I-01  DROPPING A RULE DOES NOT RENAME THE OTHERS. scanPlan() builds
 *         $plan['live'] with PRESERVED keys — it skips config-broken rules, and
 *         the per-instrument-rights gate unsets more — so the array is SPARSE
 *         and its keys are rule ordinals. identifyAll() re-indexed it densely
 *         and durableEvaluateRecord() then looked the identity up by ordinal-1,
 *         so one dropped rule shifted every later rule's name by one and pushed
 *         the last one off the end into the `unnamed:` fallback.
 *
 *         That is not a labelling bug. rule_source_id is hashed into
 *         Hmac::findingIdentity(), so a mis-attributed finding gets the IDENTITY
 *         of a rule that did not produce it — and identity is the key the
 *         incremental supersede logic matches on.
 *
 *         The check is written as a comparison rather than against a fixture,
 *         because a fixture would have to be generated by the code under test:
 *         scan the same project twice, once with a rule barred and once with it
 *         visible, and require that the rules present in BOTH runs keep the same
 *         name. That property is what a stored finding depends on and it cannot
 *         be satisfied by a dense re-index.
 *
 *   I-02  A SETTINGS RULE IS NAMED AS ONE. Origin used to be inferred from a
 *         positional `settingsCount` that no production caller ever supplied, so
 *         every settings rule was named through the annotation branch. The two
 *         branches share one namespace that the `set:` / `ann:` prefixes exist to
 *         keep apart, and the annotation branch names a rule by its FIELD LIST —
 *         so a settings rule and an annotation rule of the same family on the
 *         same field produced the same stem and were separated only by a counter
 *         assigned in list order. Deleting one renamed the other.
 *
 *         The count could not have been made correct either: Branching::resolve()
 *         drops rules that lost every field to a branch rule and appends
 *         synthesized ones, so no integer boundary survives it. Origin therefore
 *         travels ON the rule.
 *
 *   I-03  THE FINGERPRINT COVERS THE RULE SET, NOT ITS ORDER. It folded a
 *         positional ordinal in, so reordering rules — nothing added, removed or
 *         edited — made fingerprintMatches() report that the configuration had
 *         moved underneath the run. Annotation rule order follows data-dictionary
 *         field order, so moving a field in the Online Designer invalidated every
 *         resumable run on the project. identify()'s own docblock says moving a
 *         field must not rename the rule written on it; the run-level guard was
 *         contradicting the identity layer.
 *
 *   I-04  identifyAll() ANSWERS WITH THE KEYS IT WAS ASKED WITH. The unit-level
 *         statement of I-01, so a future dense re-index fails here first, with a
 *         one-line diagnosis, rather than three layers up as a wrong rule name.
 *
 * Every check below fails on the pre-fix tree. Run:  php tests/scan_identity_php.php
 */

namespace ExternalModules {
    class AbstractExternalModule {
        public $logCalls = []; public $subSettings = []; public $projectSettings = [];
        public $systemSettings = []; public $projectIdReturn = null;
        public function getSubSettings($k, $pid = null) {
            $e = ($pid !== null && $pid !== '') ? $pid : $this->projectIdReturn;
            return $e ? $this->subSettings : [];
        }
        public function getProjectSetting($k, $pid = null) {
            $e = ($pid !== null && $pid !== '') ? $pid : $this->projectIdReturn;
            if (!$e) return null;
            return isset($this->projectSettings[$k]) ? $this->projectSettings[$k] : null;
        }
        public function getSystemSetting($k) {
            return isset($this->systemSettings[$k]) ? $this->systemSettings[$k] : null;
        }
        public function setSystemSetting($k, $v) { $this->systemSettings[$k] = $v; }
        /**
         * A repeatable sub-setting is stored as ONE parallel array per sub-key,
         * indexed by row. Modelled faithfully because the minting writes the
         * whole column at once, and a mock that accepted a partial write would
         * bless exactly the bug the whole-column write exists to avoid.
         */
        public function setProjectSetting($k, $v, $pid = null) {
            $this->projectSettings[$k] = $v;
            if (is_array($v)) {
                foreach ($v as $i => $one) {
                    if (isset($this->subSettings[$i])) $this->subSettings[$i][$k] = $one;
                }
            }
        }
        public function query($sql, $params = []) { return []; }
        public function getProjectId() { return $this->projectIdReturn; }
        public function getUrl($p) { return '/x/' . $p; }
        public function log($m, $p = []) { $this->logCalls[] = [$m, $p]; return count($this->logCalls); }
        public function initializeJavascriptModuleObject() { return '<script></script>'; }
        public function getJavascriptModuleObjectName() { return 'EM.T.UV'; }
        public function getUser() { return new TestUser('nurse'); }
    }
