namespace {
    require_once __DIR__ . '/../UniversalValidator.php';

    const PID = 77;
    $n = 0; $fail = 0;
    function check($label, $cond) {
        global $n, $fail; $n++;
        if (!$cond) { $fail++; fwrite(STDERR, "FAIL: $label\n"); }
    }

    /** A dictionary from [field => [form, annotation]]. */
    function dict(array $spec) {
        $d = [];
        foreach ($spec as $f => $s) {
            $d[$f] = ['field_type' => 'text', 'form_name' => $s[0],
                      'field_annotation' => isset($s[1]) ? $s[1] : ''];
        }
        return $d;
    }

    function mkMod($dict, $data, $subs = []) {
        $m = new \INSPIRE\UniversalValidator\UniversalValidator();
        $m->subSettings = $subs;
        $m->projectSettings = ['log-values' => ''];
        $m->projectIdReturn = PID;
        \REDCap::$dictionary = $dict;
        \REDCap::$data = $data;
        return $m;
    }

    /**
     * Scan one record through the REAL seam and answer field => rule_source_id.
     *
     * Deliberately through durableScanContext()'s own evaluate closure rather
     * than by calling durableEvaluateRecord() directly: the closure is what
     * binds the plan, the generation and the identity list together, and binding
     * them is where the defect lived.
     */
    function identitiesByField($m, $recordId) {
        // The generation is REQUIRED now, and null means planning. There is no
        // default: a default is what wrote generation 1 for every run of every
        // project on the installation and wedged every second scan.
        $ctx = $m->durableScanContext(PID, ['valueCeiling' => 'locations',
                                            'generation' => 7, 'runSeq' => 7]);
        if (empty($ctx['ok'])) return ['__why' => $ctx['why']];
        $ev = $ctx['evaluate'];
        $node = \REDCap::$data[$recordId];
        $r = $ev($recordId, $node);
        $out = [];
        foreach ($r['findings'] as $f) {
            $out[$f['field']] = $f['rule_source_id'];
        }
        $out['__ords'] = [];
        foreach ($r['findings'] as $f) $out['__ords'][$f['field']] = $f['rule_ord'];
        $out['__problems'] = isset($r['problems']) ? count($r['problems']) : 0;
        return $out;
    }

    /* =====================================================================
     * I-01  dropping a rule does not rename the others
     * ===================================================================== */
    {
        // Four assert rules, one per form, each naming only its own field so
        // nothing is cross-form and every rule is independently violable. The
        // messages differ so groupMulti cannot pool them into one rule.
        $mk = function ($bAnnotation) {
            return dict([
                'record_id' => ['fa'],
                'a_val' => ['fa', '@UVASSERT={"assert":"[a_val]=\'OK\'","message":"m1","blockSave":"hard"}'],
                'b_val' => ['fb', $bAnnotation],
                'c_val' => ['fc', '@UVASSERT={"assert":"[c_val]=\'OK\'","message":"m3","blockSave":"hard"}'],
                'r_val' => ['fr', '@UVASSERT={"assert":"[r_val]=\'OK\'","message":"m4","blockSave":"hard"}'],
            ]);
        };
        $GOOD_B   = '@UVASSERT={"assert":"[b_val]=\'OK\'","message":"m2","blockSave":"hard"}';
        // Truncated JSON. The most ordinary misconfiguration there is - and
        // scanPlan goes out of its way to REPORT a config-broken rule rather
        // than drop it silently, which is exactly why the gap it leaves in
        // $plan['live'] is routine rather than exotic.
        $BROKEN_B = '@UVASSERT={"assert":';

        // Every value wrong, so every surviving rule produces exactly one finding.
        $data = [1 => [1 => ['record_id' => '1', 'a_val' => 'X', 'b_val' => 'X',
                             'c_val' => 'X', 'r_val' => 'X']]];

        // PASS 1: the rule at ordinal 2 is config-broken, so scanPlan skips it
        // and $plan['live'] becomes {0, 2, 3} - sparse, gap in the middle.
        $barred = identitiesByField(mkMod($mk($BROKEN_B), $data), 1);

        check('I-01: with one rule config-broken, the other three are still examined',
            isset($barred['a_val'], $barred['c_val'], $barred['r_val']));
        check('I-01: and the broken rule contributes no finding',
            !isset($barred['b_val']));
        // The last rule is the one that fell off the end of the dense list.
        check('I-01: no finding is filed under a placeholder rule name',
            isset($barred['r_val']) && strpos($barred['r_val'], 'unnamed:') !== 0
            && isset($barred['c_val']) && strpos($barred['c_val'], 'unnamed:') !== 0);
        check('I-01: and nothing is reported as an internal identity failure',
            isset($barred['__problems']) && $barred['__problems'] === 0);
        // The ordinals themselves are the sparse keys, which is what makes the
        // lookup index meaningful in the first place.
        check('I-01: the ordinals are the true rule positions, not compacted ones',
            isset($barred['__ords']['c_val']) && $barred['__ords']['c_val'] === 3
            && isset($barred['__ords']['r_val']) && $barred['__ords']['r_val'] === 4);

        // PASS 2: the same project, the same record, the same three surviving
        // rules - but b_val's annotation is now well-formed, so nothing is
        // dropped and $plan['live'] is dense.
        $whole = identitiesByField(mkMod($mk($GOOD_B), $data), 1);

        check('I-01: with nothing barred, all four rules are examined',
            isset($whole['a_val'], $whole['b_val'], $whole['c_val'], $whole['r_val']));

        // THE PROPERTY. A rule's name is a property of the rule, not of how many
        // OTHER rules happened to survive the plan. Under the dense re-index,
        // c_val took r_val's name in pass 1 and its own in pass 2, and r_val had
        // no name at all in pass 1 - so a finding stored by one run could never
        // be matched by the next.
        check('I-01: a rule keeps its name when an unrelated rule is dropped (a_val)',
            $barred['a_val'] === $whole['a_val']);
        check('I-01: a rule keeps its name when an EARLIER rule is dropped (c_val)',
            $barred['c_val'] === $whole['c_val']);
        check('I-01: including the last rule in the list (r_val)',
            $barred['r_val'] === $whole['r_val']);

        // And the four names are four names. A collision would make two rules
        // one rule in the store, which the identity key cannot represent.
        $names = [$whole['a_val'], $whole['b_val'], $whole['c_val'], $whole['r_val']];
        check('I-01: four rules produce four distinct identities',
            count(array_unique($names)) === 4);
    }

